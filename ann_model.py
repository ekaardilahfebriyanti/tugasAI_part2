def metrics_table(y_true, y_pred, n_classes=3):
    cm = ann_module.confusion_matrix(y_true, y_pred, n_classes)
    rows = []
    for c in range(n_classes):
        tp = cm[c, c]
        precision = tp / cm[:, c].sum() if cm[:, c].sum() else 0.0
        recall = tp / cm[c, :].sum() if cm[c, :].sum() else 0.0
        f1 = 2 * precision * recall / (precision + recall) if precision + recall else 0.0
        rows.append((CLASS_NAMES[c], precision, recall, f1, int(cm[c, :].sum())))
    table = pd.DataFrame(rows, columns=["Kelas", "Precision", "Recall", "F1", "Support"]).set_index("Kelas")
    summary = {"accuracy": float(np.trace(cm) / cm.sum()), "macro_f1": float(table["F1"].mean())}
    return table, cm, summary


def show_confusion(cm, title):
    fig, ax = plt.subplots(figsize=(4.2, 3.6))
    ax.imshow(cm, cmap="Blues")
    ax.set_xticks(range(3))
    ax.set_yticks(range(3))
    ax.set_xticklabels(CLASS_NAMES)
    ax.set_yticklabels(CLASS_NAMES)
    ax.set_xlabel("Prediksi")
    ax.set_ylabel("Aktual")
    ax.set_title(title)
    for i in range(3):
        for j in range(3):
            ax.text(j, i, cm[i, j], ha="center", va="center", color="white" if cm[i, j] > cm.max() / 2 else "black")
    plt.tight_layout()
    plt.show()


section("2.1 Gradient check (gradien analitik lawan numerik)")
rng = np.random.default_rng(SEED)
idx = rng.choice(len(X_train), size=32, replace=False)
Xg, yg = X_train[idx], y_train[idx]
names = ["relu", "tanh", "softmax"]
sizes = [X_train.shape[1], 64, 32, 3]
Wg, bg = ann_module.initialize_parameters(sizes, names, SEED)
L2 = 1e-4


def loss_fn():
    probs = ann_module.forward_pass(Xg, Wg, bg, names)[0][-1]
    return ann_module.cross_entropy_loss(yg, probs, Wg, L2)


acts, pres = ann_module.forward_pass(Xg, Wg, bg, names)
grads_W, grads_b = ann_module.backward_pass(yg, acts, pres, Wg, names, L2)

eps = 1e-5
worst = 0.0
for k, (params, grads, label) in enumerate([(Wg, grads_W, "W"), (bg, grads_b, "b")]):
    for layer in range(len(params)):
        numeric = np.zeros_like(params[layer])
        it = np.nditer(params[layer], flags=["multi_index"])
        for _ in it:
            pos = it.multi_index
            original = params[layer][pos]
            params[layer][pos] = original + eps
            loss_plus = loss_fn()
            params[layer][pos] = original - eps
            loss_minus = loss_fn()
            params[layer][pos] = original
            numeric[pos] = (loss_plus - loss_minus) / (2 * eps)
        analytic = grads[layer]
        rel = np.linalg.norm(analytic - numeric) / (np.linalg.norm(analytic) + np.linalg.norm(numeric) + 1e-12)
        worst = max(worst, rel)
        print(f"{label}{layer + 1}: galat relatif = {rel:.2e}")
print(f"\nGalat relatif terbesar = {worst:.2e} -> {'LULUS' if worst < 1e-6 else 'PERIKSA ULANG'} (batas 1e-6)")

