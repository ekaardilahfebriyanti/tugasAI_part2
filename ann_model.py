section("3.1 Grid search (skor = Macro F1 validasi pada epoch terbaik, rata-rata 5 seed)")
rows = []
t_start = time.time()
for (arch_name, (sizes, acts)), lr, l2 in itertools.product(ARCHS.items(), LRS, L2S):
    scores, epochs = [], []
    for s in SEEDS:
        m = ANN(hidden_sizes=sizes, hidden_activations=acts, learning_rate=lr, l2_lambda=l2,
                max_epochs=100, patience=15, seed=s)
        m.fit(X_train, y_train, X_val, y_val)
        scores.append(max(m.history_["val_f1"]))
        epochs.append(int(np.argmax(m.history_["val_f1"])) + 1)
    rows.append({"arsitektur": arch_name, "lr": lr, "l2": l2,
                 "f1_mean": np.mean(scores), "f1_std": np.std(scores), "epoch_terbaik_rata2": np.mean(epochs)})
    print(f"{arch_name:18s} lr={lr:<6} l2={l2:<7} F1={np.mean(scores):.4f} +- {np.std(scores):.4f}")
print(f"\nWaktu grid search : {time.time() - t_start:.1f} detik")

grid = pd.DataFrame(rows).sort_values("f1_mean", ascending=False).reset_index(drop=True)
