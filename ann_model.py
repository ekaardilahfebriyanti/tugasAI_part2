def fit_sklearn_mlp(activation, seed):
    mlp = MLPClassifier(hidden_layer_sizes=BEST_SIZES, activation=activation, solver="sgd",
                        momentum=0.9, nesterovs_momentum=False, learning_rate_init=BEST_LR,
                        learning_rate="constant", alpha=SK_ALPHA, batch_size=64, random_state=seed)
    best_f1, best_model, wait = -1.0, None, 0
    for epoch in range(100):
        mlp.partial_fit(X_train, y_train, classes=[0, 1, 2])
        f1 = metrics_table(y_val, mlp.predict(X_val))[2]["macro_f1"]
        if f1 > best_f1:
            best_f1, best_model, wait = f1, copy.deepcopy(mlp), 0
        else:
            wait += 1
            if wait >= 15:
                break
    return best_model, best_f1


