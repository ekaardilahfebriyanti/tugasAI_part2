section("4.1 Anggota scikit-learn (konfigurasi disamakan dengan versi from scratch)")
print("MLP dilatih dengan early stopping pada Macro F1 validasi, sama seperti ANN from scratch (notebook 02).")


def fit_sklearn_mlp(seed=SEED):
    mlp = MLPClassifier(hidden_layer_sizes=(64, 32), activation="tanh", solver="sgd", momentum=0.9,
                        nesterovs_momentum=False, learning_rate_init=0.01, alpha=0.001 * len(X_train),
                        batch_size=64, random_state=seed)
    best_f1, best_model, wait = -1.0, None, 0
    for _ in range(100):
        mlp.partial_fit(X_train, y_train, classes=[0, 1, 2])
        f1 = val_f1(mlp.predict(X_val))
        if f1 > best_f1:
            best_f1, best_model, wait = f1, copy.deepcopy(mlp), 0
        else:
            wait += 1
            if wait >= 15:
                break
    return best_model


sk_members = {}
