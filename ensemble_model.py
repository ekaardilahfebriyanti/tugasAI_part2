def metrics_table(y_true, y_pred, n_classes=3):
    cm = ann_module.confusion_matrix(y_true, y_pred, n_classes)
    rows = []
    for c in range(n_classes):
        tp = cm[c, c]
        precision = tp / cm[:, c].sum() if cm[:, c].sum() else 0.0
        recall = tp / cm[c, :].sum() if cm[c, :].sum() else 0.0
        f1 = 2 * precision * recall / (precision + recall) if precision + recall else 0.0
        rows.append((CLASS_NAMES[c], precision, recall, f1, int(cm[c, :].sum())))
    table = pd.DataFrame(rows, columns=["Kelas", "Precision", "Recall", "F1", "Support"]).set_index("Kelas")
    summary = {"accuracy": float(np.trace(cm) / cm.sum()), "macro_f1": float(table["F1"].mean())}
    return table, cm, summary


def show_confusion(cm, title):
    fig, ax = plt.subplots(figsize=(4.2, 3.6))
    ax.imshow(cm, cmap="Blues")
    ax.set_xticks(range(3))
    ax.set_yticks(range(3))
    ax.set_xticklabels(CLASS_NAMES)
    ax.set_yticklabels(CLASS_NAMES)
    ax.set_xlabel("Prediksi")
    ax.set_ylabel("Aktual")
    ax.set_title(title)
    for i in range(3):
        for j in range(3):
            ax.text(j, i, cm[i, j], ha="center", va="center", color="white" if cm[i, j] > cm.max() / 2 else "black")
    plt.tight_layout()
    plt.show()


