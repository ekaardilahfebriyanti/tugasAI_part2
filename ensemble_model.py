def sk_vote(models, X, voting):
    if voting == "hard":
        preds = np.array([m.predict(X) for m in models.values()])
        return np.array([np.bincount(preds[:, i], minlength=3).argmax() for i in range(preds.shape[1])])
    return np.mean([m.predict_proba(X) for m in models.values()], axis=0).argmax(axis=1)


vote_rows = []
for voting in ["hard", "soft"]:
    t0 = time.time()
    pred = sk_vote(sk_members, X_val, voting)
    infer_ms = (time.time() - t0) * 1000
    s = metrics_table(y_val, pred)[2]
    vote_rows.append({"Ensemble": f"sklearn {voting} voting", "Accuracy": s["accuracy"], "Macro F1": s["macro_f1"],
                      "Inferensi val (ms)": infer_ms})
for label in ens_results:
    s = ens_results[label]["summary"]
    vote_rows.append({"Ensemble": f"scratch hard, {label.replace('Ensemble ', '')}", "Accuracy": s["accuracy"],
                      "Macro F1": s["macro_f1"], "Inferensi val (ms)": ens_results[label]["infer_ms"]})
vote_df = pd.DataFrame(vote_rows).set_index("Ensemble")
